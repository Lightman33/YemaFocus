import { readFile } from 'node:fs/promises';

test('实际同步引擎和内存仓库：离线番茄先存本机，联网后另一设备读到同一键', async t => {
  const h = await setup();
  t.after(() => { h.p.c.dispose(); h.computer.engine.dispose(); });
  const day = '2026-11-13', columns = ['番茄', day + ' 15:00:00', day + ' 15:25:00', '25', '虚构电脑记录', '完成', '', ''];
  const existing = await recordKey(day, columns, 0);
  await h.computer.engine.commit(updateUnit(h.computer.engine.getState(), existing, 'computer', { day, columns }));
  h.clock.advance();
  await h.computer.engine.syncNow();
  await h.p.c.join();
  assert.equal(h.p.source.snapshot().records.length, 1);
  const timer = new FocusTimer({ store: h.p.store, source: h.p.source, now: h.clock.now, newId: () => 'fictional-mobile-session' });
  await timer.refresh(); await timer.saveMinutes(1, 5);
  h.p.online(false);
  await timer.act('start', { taskId: 't' }); h.clock.advance(MINUTE * 2);
  assert.equal((await timer.advance(true)).message, '专注完成');
  const mobile = h.p.source.snapshot().records.find(r => r.columns[7] === 't|电脑上的虚构任务');
  assert.ok(mobile);
  const key = await recordKey(day, mobile.columns, 0);
  assert.equal(bucketOf(key), 'records-2026-11');
  assert.equal(todayFocus(h.p.source.snapshot()).count, 2);
  assert.equal(todayFocus(h.p.source.snapshot()).minutes, 26);
  assert.equal(h.computer.engine.getState().units[key], undefined);
  h.p.online(true);
  h.clock.advance(); await h.p.c.syncNow(); await h.computer.engine.syncNow();
  const read = unitInfo(h.computer.engine.getState().units[key]);
  assert.deepEqual(read.preferred.value, { day, columns: mobile.columns });
  assert.equal(read.preferred.sources[0].stamp.focusSession, 'fictional-mobile-session');
  assert.equal((await h.p.store.readMetadata()).record.settings.focusTimer.workMinutes, 1);
  assert.equal(h.computer.engine.getState().units['["setting","focusTimer"]'], undefined);
});

test('记录冲突可以在专注页明确保留一份，之后同步到另一设备', async t => {
  const h = await setup();
  t.after(() => { h.p.c.dispose(); h.computer.engine.dispose(); });
  const day = '2026-11-13', columns = ['番茄', day + ' 15:00:00', day + ' 15:25:00', '25', '虚构冲突记录', '完成', '', ''];
  const key = await recordKey(day, columns, 0);
  const live = updateUnit(h.computer.engine.getState(), key, 'computer', { day, columns });
  const deleted = deleteUnit(emptyState(), key, 'computer-a');
  await h.computer.engine.commit(merge(live, deleted));
  h.clock.advance(); await h.computer.engine.syncNow(); await h.p.c.join();
  const document = parseDocument(await readFile(new URL('../../index.html', import.meta.url), 'utf8'));
  document.getElementById('page-focus').hidden = false;
  const timer = new FocusTimer({ store: h.p.store, source: h.p.source, now: h.clock.now });
  const view = new FocusView({ document, source: h.p.source, timer, onNotice() {}, armBell() {}, playBell() {} });
  t.after(() => view.destroy()); await view.entered();
  const panel = document.getElementById('focus-conflicts');
  assert.equal(panel.hidden, false);
  assert.match(panel.textContent, /虚构冲突记录/);
  assert.match(panel.textContent, /删除的版本/);
  const buttons = panel.querySelectorAll('button');
  assert.deepEqual([...buttons].map(b => b.textContent), ['保留这条记录']);
  assert.match(panel.textContent, /要删除请在电脑上撤销这条记录/);
  const snapshot = h.p.source.snapshot();
  const deletedBranch = snapshot.conflicts.find(c => c.key === key).candidates.find(c => c.deleted).branch;
  await assert.rejects(h.p.source.resolve(key, { branch: deletedBranch, observed: snapshot.editToken }), /要删除请在电脑上撤销这条记录/);
  buttons[0].emit('click');
  await view.pending;
  assert.equal(panel.hidden, true);
  h.clock.advance(); await h.p.c.syncNow(); await h.computer.engine.syncNow();
  const read = unitInfo(h.computer.engine.getState().units[key]);
  assert.equal(read.conflict, false);
  assert.deepEqual(read.preferred.value, { day, columns });
});
