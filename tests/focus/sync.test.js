import test from 'node:test';
import assert from 'node:assert/strict';
import { setup } from '../wiring/helpers.js';
import { FocusTimer } from '../../app/focus-timer.js';
import { todayFocus, recordKey, MINUTE } from '../../app/focus-records.js';
import { deleteUnit, updateUnit } from '../../sync/edit.js';
import { bucketOf } from '../../sync/pack.js';
import { emptyState, merge, unitInfo } from '../../sync/merge.js';
import { FocusView } from '../../app/focus-view.js';
